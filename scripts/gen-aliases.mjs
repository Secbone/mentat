#!/usr/bin/env node
// Single source of truth for workspace package aliases.
//
// Derives every `@mentat/*` alias from each package's `package.json` `exports`
// map (so a new package, or a new subpath like `@mentat/core/testing`, is
// registered in one place), then emits:
//   - tsconfig.paths.json          (consumed via `extends` in tsconfig.json)
//   - scripts/workspace-aliases.mjs (consumed by vitest.config.ts)
//
// Run with `pnpm gen`. `pnpm test` / `pnpm typecheck` regenerate first.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packagesDir = join(root, "packages");

/** Expand a package's exports map into [alias, repoRelativeTarget] pairs. */
function aliasesFor(pkgDir, manifest) {
  if (!manifest.exports) return [];
  const pairs = [];
  for (const [subpath, target] of Object.entries(manifest.exports)) {
    if (typeof target !== "string") continue;
    const alias =
      subpath === "." ? manifest.name : `${manifest.name}/${subpath.replace(/^\.\//, "")}`;
    const absolute = join(packagesDir, pkgDir, target);
    pairs.push([alias, relative(root, absolute).split("\\").join("/")]);
  }
  return pairs;
}

const entries = [];
for (const pkgDir of readdirSync(packagesDir).sort()) {
  const manifestPath = join(packagesDir, pkgDir, "package.json");
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch {
    continue;
  }
  if (!manifest.name?.startsWith("@mentat/")) continue;
  entries.push(...aliasesFor(pkgDir, manifest));
}

// Longest alias first so `@mentat/core/testing` wins over `@mentat/core`.
entries.sort((a, b) => b[0].length - a[0].length || a[0].localeCompare(b[0]));

const tsconfig = {
  compilerOptions: {
    baseUrl: ".",
    paths: Object.fromEntries(entries.map(([alias, target]) => [alias, [target]])),
  },
};
writeFileSync(join(root, "tsconfig.paths.json"), `${JSON.stringify(tsconfig, null, 2)}\n`);

const mjs = [
  "// AUTO-GENERATED by scripts/gen-aliases.mjs — do not edit by hand.",
  'import { fileURLToPath } from "node:url";',
  "",
  // biome-ignore lint/suspicious/noTemplateCurlyInString: emitted literally into the generated file
  "const resolve = (relative) => fileURLToPath(new URL(`../${relative}`, import.meta.url));",
  "",
  "export const workspaceAliases = {",
  ...entries.map(
    ([alias, target]) => `  ${JSON.stringify(alias)}: resolve(${JSON.stringify(target)}),`,
  ),
  "};",
  "",
].join("\n");
writeFileSync(join(root, "scripts", "workspace-aliases.mjs"), mjs);

console.log(`gen-aliases: wrote ${entries.length} aliases`);
